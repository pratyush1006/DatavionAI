def write_file(relative_path: str, content: str) -> None:
    """Write one RC12 source file, backing up an existing file first."""

    destination = ROOT / relative_path
    destination.parent.mkdir(parents=True, exist_ok=True)

    if destination.exists():
        backup = BACKUP_ROOT / relative_path
        backup.parent.mkdir(parents=True, exist_ok=True)
        shutil.copy2(destination, backup)

    destination.write_text(
        textwrap.dedent(content).lstrip(),
        encoding="utf-8",
    )


def verify_style(path: Path) -> None:
    """Verify the required DatavionAI Python source style."""

    source = path.read_text(encoding="utf-8")
    if not source.lstrip().startswith('"""'):
        raise AssertionError(f"RC12 style failure: {path}")
    if "from __future__ import annotations" not in source:
        raise AssertionError(f"RC12 style failure: {path}")


