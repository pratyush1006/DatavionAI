"""
Prediction selectors.
"""

from __future__ import annotations

from uuid import UUID

from django.db.models import Q, QuerySet
from django.shortcuts import get_object_or_404

from apps.ai.models import Prediction
from apps.platform.organizations.models import Organization


class PredictionSelector:
    """
    Read-only queries for predictions.

    This selector centralizes all prediction retrieval logic.
    No write operations should be implemented here.
    """

    @staticmethod
    def queryset() -> QuerySet[Prediction]:
        """
        Return the base prediction queryset.
        """

        return Prediction.objects.select_related(
            "organization",
            "patient",
            "ai_model",
        )

    @staticmethod
    def list() -> QuerySet[Prediction]:
        """
        Return all predictions.
        """

        return PredictionSelector.queryset()

    @staticmethod
    def get(
        *,
        prediction_id: UUID,
    ) -> Prediction:
        """
        Return a prediction by identifier.
        """

        return get_object_or_404(
            PredictionSelector.queryset(),
            pk=prediction_id,
        )

    @staticmethod
    def list_by_patient(
        *,
        patient_id: UUID,
    ) -> QuerySet[Prediction]:
        """
        Return predictions for a specific patient.
        """

        return PredictionSelector.queryset().filter(
            patient_id=patient_id,
        )

    @staticmethod
    def list_by_model(
        *,
        ai_model_id: UUID,
    ) -> QuerySet[Prediction]:
        """
        Return predictions generated by a specific model.
        """

        return PredictionSelector.queryset().filter(
            ai_model_id=ai_model_id,
        )

    @staticmethod
    def list_by_organization(
        *,
        organization: Organization,
    ) -> QuerySet[Prediction]:
        """
        Return predictions belonging to an organization.
        """

        return PredictionSelector.queryset().filter(
            organization=organization,
        )

    @staticmethod
    def search(
        *,
        organization: Organization,
        query: str,
    ) -> QuerySet[Prediction]:
        """
        Search predictions within an organization.
        """

        return (
            PredictionSelector.queryset()
            .filter(
                organization=organization,
            )
            .filter(
                Q(
                    prediction_type__icontains=query,
                )
                | Q(
                    risk_level__icontains=query,
                )
                | Q(
                    explanation__icontains=query,
                )
            )
        )

    @staticmethod
    def count(
        *,
        organization: Organization,
    ) -> int:
        """
        Return the number of predictions within an organization.
        """

        return PredictionSelector.list_by_organization(
            organization=organization,
        ).count()


__all__ = [
    "PredictionSelector",
]
