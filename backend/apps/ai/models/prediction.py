"""
Prediction model.
"""

from __future__ import annotations

from django.db import models

from apps.ai.constants import PredictionType, RiskLevel
from apps.core.models import BaseManager, BaseModel
from apps.platform.organizations.models import Organization


class Prediction(BaseModel):
    """
    Represents a clinical prediction generated by an AI model.
    """

    objects = BaseManager()

    organization = models.ForeignKey(
        Organization,
        on_delete=models.CASCADE,
        related_name="predictions",
        help_text="Organization that owns the prediction.",
    )

    patient = models.ForeignKey(
        "patients.Patient",
        on_delete=models.CASCADE,
        related_name="predictions",
        help_text="Patient associated with the prediction.",
    )

    ai_model = models.ForeignKey(
        "ai.AIModel",
        on_delete=models.CASCADE,
        related_name="predictions",
        help_text="AI model used for the prediction.",
    )

    prediction_type = models.CharField(
        max_length=50,
        choices=PredictionType.choices,
        help_text="Type of clinical prediction.",
    )

    risk_score = models.FloatField(
        help_text="Numerical risk score.",
    )

    risk_level = models.CharField(
        max_length=20,
        choices=RiskLevel.choices,
        help_text="Derived risk level.",
    )

    input_data = models.JSONField(
        default=dict,
        blank=True,
        help_text="Input data used for the prediction.",
    )

    result = models.JSONField(
        default=dict,
        blank=True,
        help_text="Prediction result details.",
    )

    explanation = models.TextField(
        blank=True,
        help_text="Human-readable explanation of the prediction.",
    )

    predicted_at = models.DateTimeField(
        auto_now_add=True,
        help_text="Timestamp when the prediction was generated.",
    )

    is_reviewed = models.BooleanField(
        default=False,
        help_text="Whether the prediction has been reviewed.",
    )

    reviewed_by = models.ForeignKey(
        "accounts.User",
        on_delete=models.SET_NULL,
        null=True,
        blank=True,
        related_name="reviewed_predictions",
        help_text="User who reviewed the prediction.",
    )

    reviewed_at = models.DateTimeField(
        null=True,
        blank=True,
        help_text="Timestamp when the prediction was reviewed.",
    )

    class Meta:
        db_table = "predictions"

        verbose_name = "Prediction"

        verbose_name_plural = "Predictions"

        ordering = ("-predicted_at",)

        indexes = [
            models.Index(
                fields=[
                    "organization",
                    "prediction_type",
                ],
                name="prediction_org_type_idx",
            ),
            models.Index(
                fields=[
                    "organization",
                    "predicted_at",
                ],
                name="prediction_org_predicted_idx",
            ),
            models.Index(
                fields=[
                    "organization",
                    "is_reviewed",
                ],
                name="prediction_org_reviewed_idx",
            ),
            models.Index(
                fields=[
                    "patient",
                    "predicted_at",
                ],
                name="pred_patient_predicted_idx",
            ),
            models.Index(
                fields=[
                    "ai_model",
                    "predicted_at",
                ],
                name="prediction_model_predicted_idx",
            ),
        ]

    def __str__(self) -> str:
        """
        Return the prediction display string.
        """

        return f"{self.prediction_type} - {self.risk_level} ({self.predicted_at})"


__all__ = [
    "Prediction",
]
