"""
DatavionAI Regular Expression Constants.

Centralized regular expression patterns used
throughout the platform.

Design Principles
-----------------
- Immutable
- Precompiled
- Enterprise ready
"""

from __future__ import annotations

import re
from re import Pattern
from typing import Final

###############################################################################
# Generic
###############################################################################

NON_WHITESPACE_REGEX: Final[Pattern[str]] = re.compile(r"\S+")

###############################################################################
# Email
###############################################################################

EMAIL_REGEX: Final[Pattern[str]] = re.compile(
    r"^[A-Za-z0-9._%+-]+@[A-Za-z0-9.-]+\.[A-Za-z]{2,}$"
)

###############################################################################
# Phone (E.164)
###############################################################################

PHONE_REGEX: Final[Pattern[str]] = re.compile(r"^\+?[1-9]\d{1,14}$")

###############################################################################
# UUID
###############################################################################

UUID_REGEX: Final[Pattern[str]] = re.compile(
    r"^[0-9a-fA-F]{8}-"
    r"[0-9a-fA-F]{4}-"
    r"[1-5][0-9a-fA-F]{3}-"
    r"[89abAB][0-9a-fA-F]{3}-"
    r"[0-9a-fA-F]{12}$"
)

###############################################################################
# URL
###############################################################################

URL_REGEX: Final[Pattern[str]] = re.compile(
    r"^https?://.+$",
    re.IGNORECASE,
)

###############################################################################
# Slug
###############################################################################

SLUG_REGEX: Final[Pattern[str]] = re.compile(r"^[a-z0-9]+(?:-[a-z0-9]+)*$")

###############################################################################
# Name
###############################################################################

NAME_REGEX: Final[Pattern[str]] = re.compile(r"^[A-Za-zÀ-ÿ][A-Za-zÀ-ÿ' .-]{0,99}$")

###############################################################################
# Password
#
# Minimum:
# - 8 characters
# - one uppercase
# - one lowercase
# - one digit
# - one special character
###############################################################################

PASSWORD_REGEX: Final[Pattern[str]] = re.compile(
    r"^(?=.*[a-z])"
    r"(?=.*[A-Z])"
    r"(?=.*\d)"
    r"(?=.*[@$!%*?&#^()_+=\-[\]{}|\\:;\"'<>,./~`])"
    r".{8,}$"
)

###############################################################################
# Public Exports
###############################################################################

__all__ = (
    "EMAIL_REGEX",
    "NAME_REGEX",
    "NON_WHITESPACE_REGEX",
    "PASSWORD_REGEX",
    "PHONE_REGEX",
    "SLUG_REGEX",
    "URL_REGEX",
    "UUID_REGEX",
)
